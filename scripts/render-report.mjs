#!/usr/bin/env node
// Phase 6: findings.json -> REPORT.md plus fixes/<id>.patch / .sql. No model tokens.
//   render-report.mjs <runDir>
// Patches are checked with `git apply --check` (read-only) but never applied.
import fs from 'node:fs';
import path from 'node:path';
import { loadRun, readJSON, writeFile, ensureDir, die, isMain, git } from './lib.mjs';

const ICON = { critical: '🔴', high: '🟠', medium: '🟡', low: '🔵', info: '⚪' };

function checkPatch(target, patchFile) {
  const r = git(target, ['apply', '--check', '-p1', patchFile], { timeout: 20000 });
  return r.status === 0;
}

export function render(runDir) {
  const run = loadRun(runDir);
  const doc = readJSON(path.join(runDir, 'findings.json'));
  const confirmed = doc.findings.filter((f) => f.verdict === 'confirmed');
  const needs = doc.findings.filter((f) => f.verdict === 'needs_validation');
  const fixesDir = ensureDir(path.join(runDir, 'fixes'));
  const L = [];
  L.push(`# Security report: ${path.basename(run.target)}`, '');
  L.push('> ⚠️ This report lists exploitable weaknesses in your app. Keep it private until the fixes are deployed.', '');
  L.push(`Target: \`${run.source}\` · Mode: **${run.mode}**${run.live ? ' + live checks' : ''} · ${doc.run.generated.slice(0, 16).replace('T', ' ')} UTC`, '');

  const bySev = (s) => confirmed.filter((f) => f.severity === s).length;
  L.push('## Summary', '', '| Critical | High | Medium | Low | Needs validation | Hardening notes |', '|---|---|---|---|---|---|');
  L.push(`| ${bySev('critical')} | ${bySev('high')} | ${bySev('medium')} | ${bySev('low') + bySev('info')} | ${needs.length} | ${doc.hardening.length} |`, '');
  if (!confirmed.length) L.push('No confirmed vulnerabilities. Review the items below that need validation.', '');

  if (confirmed.length) L.push('## Fix these first', '');
  for (const f of confirmed) {
    L.push(`### ${f.id} ${ICON[f.severity] || ''} ${f.severity.toUpperCase()}: ${f.title}`, '');
    L.push(`\`${f.checkId}\` · ${f.file ? `\`${f.file}${f.line ? `:${f.line}` : ''}\`` : 'live configuration'}${f.source === 'carried' ? ` · carried from ${f.carriedFrom} (code unchanged)` : ''}`, '');
    if (f.impact || f.exploit) L.push(`**What an attacker can do:** ${f.impact || f.exploit}`, '');
    if (f.reasoning) L.push(`**Why:** ${f.reasoning}`, '');
    if (f.evidence) L.push('```', f.evidence, '```', '');
    if (f.fix?.summary) L.push(`**Fix:** ${f.fix.summary}`, '');
    if (f.fix?.sql) {
      writeFile(path.join(fixesDir, `${f.id}.sql`), f.fix.sql.trim() + '\n');
      L.push('```sql', f.fix.sql.trim(), '```', `Saved to \`fixes/${f.id}.sql\`. Add it as a new migration (\`supabase migration new fix_${f.id.toLowerCase()}\`) or run it in the SQL editor.`, '');
    }
    if (f.fix?.patch) {
      const p = writeFile(path.join(fixesDir, `${f.id}.patch`), f.fix.patch.trimEnd() + '\n');
      const ok = checkPatch(run.target, p);
      L.push(`Patch: \`fixes/${f.id}.patch\` (${ok ? 'applies cleanly' : 'does not apply cleanly, so apply it by hand'}). To apply: \`git -C "${run.target}" apply "${p}"\``, '');
    }
  }

  if (needs.length) {
    L.push('## Needs validation', '', 'These could not be proven from the code alone. Each one names the fact to check.', '');
    for (const f of needs) L.push(`- **${f.id}** \`${f.checkId}\` ${f.title}${f.file ? ` (\`${f.file}${f.line ? `:${f.line}` : ''}\`)` : ''}. Check: ${f.needs}`);
    L.push('');
  }
  if (doc.hardening.length) {
    L.push('## Hardening notes', '', 'Low-risk improvements and defense-in-depth gaps. Not vulnerabilities on their own.', '');
    for (const h of doc.hardening) L.push(`- \`${h.checkId}\` ${h.title}${h.file ? ` (\`${h.file}${h.line ? `:${h.line}` : ''}\`)` : ''}${h.note ? `: ${h.note}` : ''}`);
    L.push('');
  }
  const c = doc.coverage;
  L.push('## Coverage', '', `Units: ${c.units} · hunted ${c.hunted} · unchanged since last run ${c.unchanged} · skipped ${c.skipped} · carried findings ${c.carried} · accepted risks ${c.accepted} · candidates rejected by the verifier ${doc.rejected.length}`, '');
  if (c.skipped) L.push('Skipped units are listed in `coverage-ledger.json`. Run with `--deep` to hunt them too.', '');
  L.push('## Accepting a risk', '', 'If a finding is intentional (for example a table that is meant to be public), record it so later runs skip it:', '',
    '```', `node <plugin>/scripts/run.mjs accept "${runDir}" F-00X "reason"`, '```', '');
  L.push('---', 'Generated by secure-hobby. The audit read your code and never changed it. Automated review can miss issues, so treat a clean report as a floor, not a guarantee.');
  writeFile(path.join(runDir, 'REPORT.md'), L.join('\n') + '\n');
  return { confirmed: confirmed.length, needs: needs.length, hardening: doc.hardening.length, report: path.join(runDir, 'REPORT.md') };
}

if (isMain(import.meta.url)) {
  const runDir = process.argv[2] || die('usage: render-report.mjs <runDir>');
  if (!fs.existsSync(path.join(runDir, 'findings.json'))) die('findings.json missing; run merge.mjs findings first');
  console.log(JSON.stringify(render(runDir)));
}
